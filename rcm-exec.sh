Rcm_get_list_values() {
    if [[ -n "$_available_values_from_command" && -z "$_available_values_from_command_executed" ]];then
        _available_values_from_command_executed=1
        if command -v "$_command" > /dev/null;then
            _; _.
            [ -n "$_arguments" ] && _arguments=' '"$_arguments"
            wordWrapDescriptionColorize "Value available from command: <magenta>${_command}${_arguments}</magenta>"
            mktemp=$(mktemp -p /dev/shm)
            ${_command}${_arguments} > "$mktemp"
            exit_code=$?
            while read line;do
                [ -n "$line" ] && available_values+=("$line")
            done < "$mktemp"
            rm "$mktemp"
        fi
    fi
    if [ -z "$available_values_backup" ];then
        available_values_backup=("${available_values[@]}")
    fi
    while [[ $# -gt 0 ]]; do
        ArrayRemove "$1" available_values[@]
        available_values=("${_return[@]}")
        unset _return
        shift
    done
    if [ "${#available_values[@]}" -gt 0 ];then
        if [ -n "$or_other" ];then
            printSelectOtherDialog available_values[@]
        elif [[ "${#available_values[@]}" -eq 1 && -n "$is_required" ]];then
            value="${available_values[0]}"
            _; _.
            __; _, "Available value: "; yellow "$value";  _, '.'; _.
            if [ -n "$interactive" ];then
                _; _.
                wordWrapDescription 'The one and only available value is selected.'
                userInputBooleanDefaultYes
                if [ -z "$boolean" ];then
                    value=' '
                fi
            else
                _; _.
                wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> filled with the only available value <yellow>$value</yellow> automatically." green
            fi
        else
            printSelectDialog available_values[@]
        fi
    else
        _; _.
        if [[ -n "$_available_values_from_command" && ! $exit_code -eq 0 ]];then
            is_required=
            __; _, Argument; _, ' '; _, "$parameter"; _, ' ';  _, set to skip by command,' '; _, pass; _, .; _.
        elif [[ -n "$_available_values_from_command" && -z "$or_other" ]];then
            __; _, No value available,' '; red Process Terminated; _, .; x
        else
            if [ -n "$default_value" ];then
                __; _, Leave blank will use default value.; _.
                label=$(_, 'Type the value [' 2>&1; yellow "$default_value" 2>&1; _, ']: ' 2>&1)
                __; read -p "$label" value
                [ -z "$value" ] && value=' '
            elif [ -n "$is_required" ];then
                __; read -p "Type the value: " value
            else
                __; read -p "Type the value or leave blank to skip: " value
            fi
            is_typing=1
        fi
    fi
}
Rcm_event_dispatcher() {
    # global command argument_placeholders RCM_ENVIRONMENT_VARIABLES tempfile
    local key value
    local label="$1"; shift
    local to_execute command_raw _command_arguments _command _arguments
    local line  find replace
    to_execute=`${command} --help 2>/dev/null | sed -n '/^'"$label"'[:\.]$/,$p' | sed -n '1,/^\s*$/p' | sed -n '2,/^\s*$/p'`
    if [ -n "$to_execute" ];then
        Rcm_prompt_build_command
        _.;
        until [[ -z "$to_execute" ]];do
            command_raw=`sed -n 1p <<< "$to_execute" | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//'`
            to_execute=`sed -n '2,$p' <<< "$to_execute"`
            _command_arguments=$(echo "$command_raw" | sed -n -E 's/\s*([^\)]+\))/\1/p')
            _command=$(echo "$_command_arguments" | sed -n -E 's/^([^\(]+)\(([^\)]*)\)$/\1/p')
            _arguments=$(echo "$_command_arguments" | sed -n -E 's/^([^\(]+)\(([^\)]*)\)$/\2/p')
            if command -v "$_command" > /dev/null;then
                if [ -n "$argument_placeholders" ];then
                    while read line; do
                        find=$(echo ${line} | sed -E 's|^([^:]+):.*|\1|' | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//')
                        replace=$(echo ${line} | sed -E 's|^[^:]+:(.*)|\1|' | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//')
                        # description="${description/"$find"/"$replace"}"
                        if [ -n "$_arguments" ];then
                            _arguments="${_arguments/"$find"/"$replace"}"
                        fi
                    done <<< "$argument_placeholders"
                fi
            fi
            [ -n "$_arguments" ] && _arguments=' '"$_arguments"
            chapter "$label" command.
            code ${_command}${_arguments}
            ____

            if [ -z "$tempfile" ];then
                tempfile=$(mktemp -p /dev/shm -t rcm.XXXXXX)
            fi
            RCM_PROMPT_CHAIN= INDENT+="$RCM_INDENT" ${_command}${_arguments} \
                > "$tempfile" \
                ; [ ! $? -eq 0 ] && { rm "$tempfile"; x; }

            while IFS= read -r to_export; do
                key=$(cut -d= -f1 <<< "$to_export")
                value=$(cut -d= -f2- <<< "$to_export")
                [ -z "$value" ] && value=-
                code export "$key"="$value"
                export "$key"="$value"
                [ -n "$RCM_ENVIRONMENT_VARIABLES" ] && RCM_ENVIRONMENT_VARIABLES+=" "
                RCM_ENVIRONMENT_VARIABLES+="${key}=${value}"
            done < "$tempfile"
            if [ -s "$tempfile" ];then
                ____
            fi

        done
    fi
}


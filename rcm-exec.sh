ArrayDiff() {
    # Computes the difference of arrays.
    #
    # Globals:
    #   Modified: _return
    #
    # Arguments:
    #   1 = Parameter of the array to compare from.
    #   2 = Parameter of the array to compare against.
    #
    # Returns:
    #   None
    #
    # Example:
    #   ```
    #   my=("cherry" "manggo" "blackberry" "manggo" "blackberry")
    #   yours=("cherry" "blackberry")
    #   ArrayDiff my[@] yours[@]
    #   # Get result in variable `$_return`.
    #   # _return=("manggo" "manggo")
    #   ```
    local e
    local source=("${!1}")
    local reference=("${!2}")
    _return=()
    # inArray is alternative of ArraySearch.
    inArray () {
        local e match="$1"
        shift
        for e; do [[ "$e" == "$match" ]] && return 0; done
        return 1
    }
    if [[ "${#reference[@]}" -gt 0 ]];then
        for e in "${source[@]}";do
            if ! inArray "$e" "${reference[@]}";then
                _return+=("$e")
            fi
        done
    else
        _return=("${source[@]}")
    fi
}
ArrayUnique() {
    # Removes duplicate values from an array.
    #
    # Globals:
    #   Modified: _return
    #
    # Arguments:
    #   1 = Parameter of the input array.
    #
    # Returns:
    #   None
    #
    # Example:
    #   ```
    #   my=("cherry" "manggo" "blackberry" "manggo" "blackberry")
    #   ArrayUnique my[@]
    #   # Get result in variable `$_return`.
    #   # _return=("cherry" "manggo" "blackberry")
    #   ```
    local e source=("${!1}")
    # inArray is alternative of ArraySearch.
    inArray () {
        local e match="$1"
        shift
        for e; do [[ "$e" == "$match" ]] && return 0; done
        return 1
    }
    _return=()
    for e in "${source[@]}";do
        if ! inArray "$e" "${_return[@]}";then
            _return+=("$e")
        fi
    done
}
wordWrapDescription() {
    local paragraph="$1" indent_first_line=$2 words_array
    local current_line first_line last
    local max=0
    local min=0
    local _indent_first_line
    [ -z "$indent_first_line" ] && indent_first_line=1
    indent_first_line=$((indent_first_line*${#RCM_INDENT}))
    _indent_first_line=$((indent_first_line + 2))
    # Angka 2 adalah tambahan dari '# '.
    max=$(tput cols)
    _max=$((100 + ${#INDENT} + $_indent_first_line))
    if [ $max -gt $_max ];then
        max=100
        min=80
    else
        max=$((max - ${#INDENT} - 6))
        min="$max"
    fi

    local i=0
    words_array=($paragraph)
    local count="${#words_array[@]}"
    current_line=
    first_line=1
    for each in "${words_array[@]}"; do
        let i++
        [ "$i" == "$count" ] && last=1 || last=
        if [ -z "$current_line" ]; then
            if [ -n "$first_line" ];then
                first_line=
                current_line="$each"
                _; printf %"${indent_first_line}"s >&2; _, "$each"
            else
                current_line="$each"
                _; printf %"${indent_first_line}"s >&2; _, "$each"
            fi
            if [ -n "$last" ];then
                _.
            fi
        else
            _current_line="${current_line} ${each}"
            if [ "${#_current_line}" -le $min ];then
                current_line+=" ${each}"
                _, " ${each}"
                if [ -n "$last" ];then
                    _.
                fi
            elif [ "${#_current_line}" -le $max ];then
                _, " ${each}"; _.
                current_line=
            else
                _.;
                _; printf %"${indent_first_line}"s >&2;
                _, "$each"
                current_line="$each"
                if [ -n "$last" ];then
                    _.
                fi
            fi
        fi
    done
}
wordWrapDescriptionColorize() {
    cleaningTag() {
        # global each
        # global color
        local string="$1"
        opentag=$(echo "$string" | grep -E -o '<[^</>]+>')
        if [ -n "$opentag" ];then
            color=$(echo "$opentag" | grep -E -o '[^<>]+')
            string=${string//"$opentag"/}
            closetag="</${color}>"
            if grep -q -F "$closetag" <<< "$string";then
                color_stop=1
                string=${string//"$closetag"/}
            fi
        fi
        each="$string"
    }
    cleaningCloseTag() {
        # global each
        # global color
        local string="$1"
        closetag="</${color}>"
        if grep -q -F "$closetag" <<< "$string";then
            color_stop=1
            string=${string//"$closetag"/}
        fi
        each="$string"
    }
    colorStop() {
        # global color_stop
        if [ -n "$color_stop" ];then
            color=$default_color
            color_stop=
        fi
    }
    local paragraph="$1" words_array default_color="$2"
    [ -z $default_color ] && default_color=_,
    color="$default_color"
    local current_line first_line last
    local max=0
    local min=0
    max=$(tput cols)
    # Angka 6 adalah 4+2.
    # Angka 4 adalah tambahan indent.
    # Angka 2 adalah tambahan dari '# '.
    _max=$((100 + ${#INDENT} + ${#RCM_INDENT} + 2))
    if [ $max -gt $_max ];then
        max=100
        min=80
    else
        max=$((max - ${#INDENT} - ${#RCM_INDENT} - 2))
        min="$max"
    fi
    local i=0
    words_array=($paragraph)
    local count="${#words_array[@]}"
    current_line=
    first_line=1

    wordWrapSentence() {
        for each in "${words_array[@]}"; do
            cleaningTag "$each"
            cleaningCloseTag "$each"
            let i++
            [ "$i" == "$count" ] && last=1 || last=
            if [ -z "$current_line" ]; then
                if [ -n "$first_line" ];then
                    first_line=
                    current_line="$each"
                    __; $color "$each"
                else
                    current_line="$each"
                    __; $color "$each"
                fi
                if [ -n "$last" ];then
                    _.
                fi
            else
                _current_line="${current_line} ${each}"
                if [ "${#_current_line}" -le $min ];then
                    current_line+=" ${each}"
                    $color " ${each}"
                    if [ -n "$last" ];then
                        _.
                    fi
                elif [ "${#_current_line}" -le $max ];then
                    $color " ${each}"; _.
                    current_line=
                else
                    _.; __; $color "$each"
                    current_line="$each"
                    if [ -n "$last" ];then
                        _.
                    fi
                fi
            fi
            colorStop
        done
    }
    temp=$(wordWrapSentence 2>&1)
    echo "$temp" >&2
}

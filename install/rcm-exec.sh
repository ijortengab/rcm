    _; _.
    __ Press the yellow key to select.
    while true; do
        __; read -rsn 1 -p "Select: " char
        if [ -z "$char" ];then
            char=y
        fi
        case $char in
            y|Y) echo "$char" >&2; boolean=1; break;;
            n|N) echo "$char" >&2; break ;;
            $'\33') echo "n" >&2; break ;;
            *) echo >&2
        esac
    done
}

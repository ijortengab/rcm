# Parse arguments. Generated by parse-options.sh
_new_arguments=()
_n=
while [[ $# -gt 0 ]]; do
    case "$1" in
        --help|-h) help=1; shift ;;
        --version|-V) version=1; shift ;;
        --config=*) config="${1#*=}"; shift ;;
        --config) if [[ ! $2 == "" && ! $2 =~ (^--$|^-[^-]|^--[^-]) ]]; then config="$2"; shift; fi; shift ;;
        --interactive|-i) interactive=1; shift ;;
        --non-interactive) interactive=0; shift ;;
        --prompt|-p) prompt=1; shift ;;
        --slow|-s) fast=0; shift ;;
        --timer|-t) timer=1; shift ;;
        --verbose|-v) verbose="$((verbose+1))"; shift ;;
        --yes|-y) autoyes=1; shift ;;
        -[^-]*) _new_arguments+=("$1"); shift ;;
        --)
            while [[ $# -gt 0 ]]; do
                case "$1" in
                    *) _new_arguments+=("$1"); shift ;;
                esac
            done
            ;;
        --[^-]*) shift ;;
        *)
            while [[ $# -gt 0 ]]; do
                case "$1" in
                    *) _new_arguments+=("$1"); shift ;;
                esac
            done
            ;;
    esac
done
set -- "${_new_arguments[@]}"
_new_arguments=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        -[^-]*) OPTIND=1
            while getopts ":hVipstvy" opt; do
                case $opt in
                    h) help=1 ;;
                    V) version=1 ;;
                    i) interactive=1 ;;
                    p) prompt=1 ;;
                    s) fast=0 ;;
                    t) timer=1 ;;
                    v) verbose="$((verbose+1))" ;;
                    y) autoyes=1 ;;
                esac
            done
            _n="$((OPTIND-1))"
            _n=${!_n}
            shift "$((OPTIND-1))"
            if [[ "$_n" == '--' ]];then
                while [[ $# -gt 0 ]]; do
                    case "$1" in
                        *) _new_arguments+=("$1"); shift ;;
                    esac
                done
            fi
            ;;
        --) shift
            while [[ $# -gt 0 ]]; do
                case "$1" in
                    *) _new_arguments+=("$1"); shift ;;
                esac
            done
            ;;
        *)
            while [[ $# -gt 0 ]]; do
                case "$1" in
                    *) _new_arguments+=("$1"); shift ;;
                esac
            done
            ;;
    esac
done
set -- "${_new_arguments[@]}"
unset _new_arguments
unset _n

# Functions. Help and Version.
printVersion() {
    echo $RCM_VERSION
}
usage() {
    title Rapid Construct Massive
    _ 'Version '; yellow $RCM_VERSION; _.
    _ 'URL '; yellow git.io/rcm; _.
    _.
cat << EOF
Usage: rcm [options]
       rcm <extension> [options]
       rcm [options] <extension> [options]

Options:
   --version
        Print version of this script.
   --help
        Show this help.
   --slow, -s
        Add delay every subtask.
   --yes, -y
        Skip every question and use the default value even the default value is equivalent to negate.
   --interactive, -i
        Display the user input if needed.
   --non-interactive
        Run without ever asking for user input. Default action.
   --verbose, -v
        Verbose mode. Causes rcm to print debugging messages about its progress.
        Multiple -v options increase the verbosity.
        The maximum is 3.
EOF
}

# Help and Version.
[ -n "$help" ] && { usage; exit 1; }
[ -n "$version" ] && { printVersion; exit 1; }

# If not set in argument, try load from environment.
# Didapat dari export oleh rcm parent process.
# Untuk fast dan verbose, maka child mengikuti parent.
[ -z "$fast" ] && fast="$RCM_FAST"
[ -z "$verbose" ] && verbose="$RCM_VERBOSE"

# Boolean default to TRUE.
[ -z "$fast" ] && fast=1; [ "$fast" == 0 ] && fast=

# Verbosity.
RCM_QUIET=; RCM_LOUD=; RCM_LOUDER=; RCM_DEBUG=;
[[ -z "$verbose" || "$verbose" -lt 1 ]] && RCM_QUIET=1 || RCM_QUIET=
[[ "$verbose" -gt 0 ]] && RCM_LOUD=1
[[ "$verbose" -gt 1 ]] && RCM_LOUD=1 && RCM_LOUDER=1
[[ "$verbose" -gt 2 ]] && RCM_LOUD=1 && RCM_LOUDER=1 && RCM_DEBUG=1

# Define variables and constants.
[ -z "$RCM_LOG" ] && { [ "$EUID" -ne 0 ] && RCM_LOG=$HOME/rcm.log || RCM_LOG=/var/log/rcm.log; }
tempfile=
exit_code=0

# Functions.
build-command-config() {

    array="$RCM_PROMPT_YAML"
    array --unset _preview
    array --unset _prepopulate_argument_non_options

    tempfile=$(mktemp -t rcm.config.XXXXXX.yml)
    echo "$array" > "$tempfile"
    words_array+=(rcm --config="$tempfile" )
    words_array+=("${RCM_EXTENSION_CHAIN[@]}")
    echo-wrap-multiline
}

build-command-non-interactive() {
    local each
    local rcm_options=
    local rcm_options_array=()
    local words_array=()
    # Jika non interactive, maka dipaksa tidak ada -i dan otomatis
    # tidak ada -y
    # [ -n "$interactive" ] && rcm_options_array+=(i)
    # [ -n "$autoyes" ] && rcm_options_array+=(y)
    # [ -n "$prompt" ] && rcm_options_array+=(p)
    [ -n "$timer" ] && rcm_options_array+=(t)
    [ -z "$fast" ] && rcm_options_array+=(s)
    if [ -n "$verbose" ];then
        for ((i = 0 ; i < "$verbose" ; i++)); do
            rcm_options_array+=(v)
        done
    fi
    for each in "${rcm_options_array[@]}";do
        rcm_options+="$each"
    done
    [ -n "$rcm_options" ] && rcm_options="-${rcm_options}"
    words_array+=(rcm $rcm_options)
    words_array+=("${RCM_EXTENSION_CHAIN[@]}")
    words_array+=("${RCM_ARGUMENT_PASS_QUOTED[@]}")
    echo-wrap-multiline
}

do-prompt() {

    RCM_CONTENTS=`$command_file_sh --help 2>/dev/null`

    source "${RCM_LIB}"/functions/rcm/rcm-prompt.sh
    backup_storage=$HOME'/.cache/rcm/rcm.'$command_file'.bak'
    history_storage=$HOME'/.cache/rcm/rcm.'$command_file'.history'

    RCM_ARGUMENT_PASS=()
    RCM_ARGUMENT_PREVIEW=()
    RCM_ARGUMENT_PASS_QUOTED=()
    RCM_ARGUMENT_PLACEHOLDERS=
    RCM_ARGUMENT_PASS_CONFIG=
    rcm-prompt
    trap x SIGINT
    [ -f "$backup_storage" ] && rm "$backup_storage"
    [ -n "$tempfile" ] && rm "$tempfile"

    echo "$RCM_PROMPT_YAML"
}

do-execute() {
    set -- "${RCM_ARGUMENT_PASS[@]}"
    if [ -n "$timer" ];then
        chapter Timer Start.
        _ Begin: $(date +%Y%m%d-%H%M%S); _.
        RCM_BEGIN=$SECONDS
        ____
    fi
    if [ -n "$is_dialog_printed" ];then
        ____
    fi
    INDENT+="${is_intro_printed:+$RCM_INDENT}" $command_file_sh "$@"
    exit_code=$?
    if [ -n "$timer" ];then
        chapter Timer Finish.
        _ End: $(date +%Y%m%d-%H%M%S); _.
        RCM_END=$SECONDS
        duration=$(( RCM_END - RCM_BEGIN ))
        hours=$((duration / 3600)); minutes=$(( (duration % 3600) / 60 )); seconds=$(( (duration % 3600) % 60 ));
        runtime=`printf "%02d:%02d:%02d" $hours $minutes $seconds`
        _ Duration: $runtime; if [ $duration -gt 60 ];then _, " (${duration} seconds)"; fi; _, '.'; _.
        ____
    fi
}

do-interactive() {
    while true; do
        RCM_CONTENTS=`$command_file_sh --help 2>/dev/null`
        if [ -z "$RCM_CONTENTS" ];then
            do-execute
            break
        fi

        source "${RCM_LIB}"/functions/rcm/rcm-prompt.sh
        backup_storage=$HOME'/.cache/rcm/rcm.'$command_file'.bak'
        history_storage=$HOME'/.cache/rcm/rcm.'$command_file'.history'

        RCM_ARGUMENT_PASS=()
        RCM_ARGUMENT_PREVIEW=()
        RCM_ARGUMENT_PASS_QUOTED=()
        RCM_ARGUMENT_PLACEHOLDERS=
        RCM_ARGUMENT_PASS_CONFIG=
        if [ -z "$is_intro_printed" ];then

            title rcm
            ____

            chapter Prepare argument for command '`'$command'`'.
            is_intro_printed=1

        fi
        rcm-prompt
        trap x SIGINT
        [ -f "$backup_storage" ] && rm "$backup_storage"
        [ -n "$tempfile" ] && rm "$tempfile"

        # Export variables part 2.
        export RCM_PROMPT_YAML="$RCM_PROMPT_YAML"

        # Build command.
        chapter Command has been built.
        _ Use command below to arrive in this position with non-interactive mode.; _.
        if [ -n "$RCM_ARGUMENT_PASS_CONFIG" ];then
            build-command-config
        else
            build-command-non-interactive
        fi
        ____

        if [ -n "$autoyes" ];then
            do-execute
            break
        fi

        chapter Execute:
        read-true
        if [ -z "$RCM_BOOLEAN" ];then
            break
        fi
        do-execute
        break
    done
}

parse-prompt-yaml() {
    array="$RCM_PROMPT_YAML"
    trap x SIGTERM
    spinning-dot 'Config loading' &
    pid=$!
    array "${RCM_EXTENSION_CHAIN[@]}"
    kill $pid
    printf "\r\033[K" >&2
    array_local=("${_return_array[@]}")
    if [ "${#array_local[@]}" -gt 0 ];then
        RCM_ARGUMENT_PASS=()
        for each in "${array_local[@]}";do
            array="$each"
            array parameter; parameter="$_return_value"
            array type; type="$_return_value"
            case "$type" in
                flag)
                    array flag; flag="$_return_value"
                    if [ -n "$flag" ];then
                        RCM_ARGUMENT_PASS+=("${parameter}")
                    fi
                    ;;
                value)
                    array value; value="$_return_value"
                    if [ -n "$value" ];then
                        RCM_ARGUMENT_PASS+=("${parameter}=${value}")
                    fi
                    ;;
                flag_value)
                    array flag; flag="$_return_value"
                    if [ -n "$flag" ];then
                        array value; value="$_return_value"
                        if [ -n "$value" ];then
                            RCM_ARGUMENT_PASS+=("${parameter}=${value}")
                        else
                            RCM_ARGUMENT_PASS+=("${parameter}")
                        fi
                    fi
                    ;;
                increment)
                    array count; count="$_return_value"
                    if [ -n "$count" ];then
                        for ((i = 0 ; i < $count ; i++)); do
                            RCM_ARGUMENT_PASS+=("${parameter}")
                        done
                    fi
                    ;;
                multivalue)
                    array values; values=("${_return_array[@]}")
                    if [ "${#values[@]}" -gt 0 ];then
                        for value in "${values[@]}"; do
                            RCM_ARGUMENT_PASS+=("${parameter}=${value}")
                        done
                    fi
                    ;;
                flag_multivalue)
                    array flag; flag="$_return_value"
                    array values; values=("${_return_array[@]}")
                    if [ -n "$flag" ];then
                        if [ "${#values[@]}" -gt 0 ];then
                            for value in "${values[@]}"; do
                                RCM_ARGUMENT_PASS+=("${parameter}=${value}")
                            done
                        else
                            RCM_ARGUMENT_PASS+=("${parameter}")
                        fi
                    fi
                    ;;
            esac
        done
    else
        RCM_ARGUMENT_PASS=("${RCM_PREPOPULATE_ARGUMENTS[@]}")
    fi
}

build-options() {
    local rcm_options_array=()
    # Reset.
    rcm_options=
    [ -n "$interactive" ] && rcm_options_array+=(i)
    [ -n "$autoyes" ] && rcm_options_array+=(y)
    [ -n "$prompt" ] && rcm_options_array+=(p)
    [ -n "$timer" ] && rcm_options_array+=(t)
    [ -z "$fast" ] && rcm_options_array+=(s)
    if [ -n "$verbose" ];then
        for ((i = 0 ; i < "$verbose" ; i++)); do
            rcm_options_array+=(v)
        done
    fi
    for each in "${rcm_options_array[@]}";do
        rcm_options+="$each"
    done
    [ -n "$rcm_options" ] && rcm_options="-${rcm_options}"

}

intro() {
    usage >/dev/null | head -3
    _ Try; blue ' 'rcm; magenta ' '--help; _, ' 'for more information.; _.
    e; _.
    _ Do you want to list available command?; _.
    read-true
    if [ -z "$RCM_BOOLEAN" ];then
        x
    fi
    e; _.
}

if [ $# -eq 0 ];then
    intro
fi

# Requirement, validate, and populate value.
if [ -f "$config" ];then
    RCM_PROMPT_YAML=$(< "$config")
    export RCM_PROMPT_YAML="$RCM_PROMPT_YAML"
fi
prefix="$RCM_LIB"
RCM_EXTENSION_CHAIN=()
command="rcm"
is_intro_printed=
is_required=1
parameter=command
parameter_plural=commands
is_dialog_printed=
until [[ ! -d "$prefix/commands" ]];do
    list=(`ls "$prefix/commands"`)
    if [ -n "$1" ];then
        value="$1"; shift
        if ! ArraySearch "$value" list[@];then
            error Command unknown: '`'"$value"'`'.; x
        fi
        unset _return
        command+=" ${value}"
    else
        if [ -z "$is_intro_printed" ];then

            title rcm
            ____

            chapter Prepare argument for command '`'$command'`'.
            is_intro_printed=1
        fi
        _; _.
        _ Select available command to execute.; _.
        print-select-dialog list[@] "$parameter" "$parameter_plural"
        is_dialog_printed=1
        _; _.
        command+=" ${value}"
        build-options
        _; _, Execute' '; magenta ${command/rcm/rcm ${rcm_options}}; _.
    fi
    prefix+=/commands/$value
    RCM_EXTENSION_CHAIN+=("$value")
    value=
done
if [ -n "$is_dialog_printed" ];then
    while true; do
        if [ -n "$prompt" ];then
            break
        fi
        if [ -n "$config" ];then
            break
        fi
        if [ -z "$interactive" ];then
            _; _.
            _ Do you want to enable --interactive option?; _.
            read-true
            if [ -n "$RCM_BOOLEAN" ];then
                interactive=1
                build-options
                _; _.
                _; _, Execute' '; magenta ${command/rcm/rcm ${rcm_options}}; _.

            fi
            break
        fi
        break
    done
fi

# Populate $command_file and $command_file_sh
command_file="rcm"
for each in "${RCM_EXTENSION_CHAIN[@]}"; do
    command_file+="-${each}"
done
command_file_sh="${command_file}.sh"

PATH="$prefix":"$PATH"
command -v "$command_file_sh" >/dev/null || { red "Unable to proceed, $command_file_sh command not found."; x; }

RCM_PREPOPULATE_ARGUMENTS=()
RCM_PREPOPULATE_ARGUMENT_NON_OPTIONS=()

while [ $# -gt 0 ]; do
    case "$1" in
        --) shift
            while [ $# -gt 0 ]; do
                 case "$1" in
                    *)
                        RCM_PREPOPULATE_ARGUMENT_NON_OPTIONS+=("$1")
                        shift
                 esac
            done
            ;;
        *)
            RCM_PREPOPULATE_ARGUMENTS+=("$1")
            shift
    esac
done

# Export variables part 1.
# Boolean export as 0 or 1. Must not leave empty string.
export RCM_FAST=$([ -n "$fast" ] && echo 1 || echo 0)
export RCM_VERBOSE="$verbose"
export RCM_LIB="$RCM_LIB"
export RCM_INDENT="$RCM_INDENT"
if [ -z "$RCM_MAIN_PID" ];then
    RCM_MAIN_PID=$$
    export RCM_MAIN_PID="$RCM_MAIN_PID"
fi

while true; do
    if [ -n "$prompt" ];then
        do-prompt
        break
    fi
    if [ -n "$interactive" ];then
        do-interactive
        break
    fi
    if [ -n "$RCM_PROMPT_YAML" ];then
        # Variable RCM_PROMPT_YAML didapat dari rcm -i command
        # Kemudian ada plugin yang mengeksekusi rcm command
        # tanpa -i dan tanpa -p
        parse-prompt-yaml
        do-execute
        break
    fi
    RCM_ARGUMENT_PASS=("${RCM_PREPOPULATE_ARGUMENTS[@]}")
    do-execute
    break
done

exit $exit_code


        _dependency=$(echo "$_help" | sed -n '/^Dependency:/,$p' | sed -n '1,/^\s*$/p' | sed -n '2,/^\s*$/p' | sed 's/^ *//g' | grep -E '(^rcm|^rcm-[^:]+|[^:]+\.sh)(:[^:]+)*$')
        if [ -n "$_dependency" ];then

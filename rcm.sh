    Rcm_resolve_dependencies_execute() {
        # global command_required_raw
        local command_required command_required_version=
        local command_required_exists command_existing_version command_required_exists_updated
        if grep -q -F : <<< "$command_required_raw";then
            command_required=$(cut -d: -f1 <<< "$command_required_raw")
            command_required_version=$(cut -d: -f2 <<< "$command_required_raw")
        else
            command_required="$command_required_raw"
            if Rcm_is_internal "$command_required_raw";then
                command_required_version="$rcm_version"
            fi
        fi
        case "$command_required" in
            rcm-install)
                if ! command -v rcm-install > /dev/null;then
                    Rcm_init rcm-install
                fi
                if [ -z "$display_waiting" ];then
                    _.
                else
                    printf "\r\033[K" >&2
                fi
                return 0
                ;;
            rcm-update)
                if ! command -v rcm-update > /dev/null;then
                    Rcm_init rcm-update
                fi
                if [ -z "$display_waiting" ];then
                    _.
                else
                    printf "\r\033[K" >&2
                fi
                return 0
                ;;
            *)
                if command -v "$command_required" > /dev/null;then
                    if ! command -v rcm-update > /dev/null;then
                        Rcm_init rcm-update
                    fi
                    command_required_exists=1
                    command_existing_version=$("$command_required" --version)
                    if [ -z "$command_required_version" ];then
                        command_required_version="$command_existing_version"
                        command_required_exists_updated=1
                    else
                        if [[ "$command_required_version" == "$command_existing_version" ]];then
                            command_required_exists_updated=1
                        else
                            command_required_exists_updated=
                        fi
                    fi
                else
                    if ! command -v rcm-install > /dev/null;then
                        Rcm_init rcm-install
                    fi
                    command_required_exists=
                fi
        esac
        if [ -z "$display_waiting" ];then
            _ Requires command:' '; magenta "$command_required"
            if [ -n "$command_required_exists" ];then
                if [ -n "$command_required_version" ];then
                    _, ':'"$command_required_version"
                fi
                if [ -n "$command_required_exists_updated" ];then
                    green ' [FOUND]'; _, .; _.
                else
                    yellow ' [UPDATE]'; _, .; _.
                fi
            else
                red ' [NOTFOUND]'; _, .; _.
            fi
        fi
        if [ -n "$command_required_exists" ];then
            if [ -z "$command_required_exists_updated" ];then
                Rcm_resolve_dependencies_update
            fi
        else
            Rcm_resolve_dependencies_install
            command_required_version=$("$command_required" --version)
        fi

        Rcm_resolve_dependencies_insert_table
    }
    PATH="${BINARY_DIRECTORY}:${PATH}"
    local commands_required_raw=() command_required_raw="$1"

    if [ -z "$display_waiting" ];then
        chapter Resolve Dependency.
    fi

    # Tambahkan rcm sebagai dependency.
    if ! grep -q -F -- "rcm ${rcm_version}" <<< "$table_dependencies";then
        table_dependencies+="rcm ${rcm_version}"$'\n'
    fi

    Rcm_resolve_dependencies_execute

    until [[ ${#commands_required_raw[@]} -eq 0 ]];do
        for command_required_raw in "${commands_required_raw[@]}"; do
            Rcm_resolve_dependencies_execute
            _command_required_raw=("$command_required_raw")
            ArrayDiff commands_required_raw[@] _command_required_raw[@]
            commands_required_raw=("${_return[@]}")
            unset _return
            unset _command_required_raw
        done
    done
    if [ -z "$display_waiting" ];then
        ____
    else
        printf "\r\033[K" >&2
    fi
}
wordWrapCommand() {
    # global words_array
    local inline_description="$1"
    local current_line first_line
    declare -i max
    declare -i min

    max=$(tput cols)
    # Angka 2 adalah tambahan dari ' \'.
    _max=$((100 + ${#INDENT} + 2))
    if [ $max -gt $_max ];then
        max=100
        min=80
    else
        max=$((max - ${#INDENT} - 2))
        min="$max"
    fi

    declare -i i; i=0
    local count="${#words_array[@]}"
    current_line=
    first_line=1
    for each in "${words_array[@]}"; do
        i+=1
        [ "$i" == "$count" ] && last=1 || last=
        if [ -z "$current_line" ]; then
            if [ -z "$first_line" ];then
                current_line="${RCM_INDENT}${each}"
                e; magenta "${RCM_INDENT}$each";
            else
                first_line=
                if [ -n "$inline_description" ];then
                    e; _, "${inline_description} "; magenta "$each"
                    current_line="${inline_description} ${each}"
                else
                    e; magenta "$each"
                    current_line="$each"
                fi
            fi
            if [ -n "$last" ];then
                _.
            fi
        else
            _current_line="${current_line} ${each}"
            if [ "${#_current_line}" -le $min ];then
                if [ -n "$last" ];then
                    _, ' '; magenta "$each"; _.
                else
                    _, ' '; magenta "$each"
                fi
                current_line+=" ${each}"
            elif [ "${#_current_line}" -le $max ];then
                if [ -n "$last" ];then
                    _, ' '; magenta "${each}"''; _.
                else
                    _, ' '; magenta "${each}"' \'; _.
                fi
                current_line=
            else
                magenta ' \'; _.; e; magenta "${RCM_INDENT}$each"
                current_line="${RCM_INDENT}${each}"
                if [ -n "$last" ];then
                    _.
                fi
            fi
        fi
    done
}
wordWrapList() {
    # global words_array
    local inline_description="$1"
    local current_line first_line last
    declare -i max
    declare -i min

    max=$(tput cols)
    # Angka 11 adalah 4+2+5.
    # Angka 4 adalah tambahan indent.
    # Angka 2 adalah tambahan dari '# '.
    # Angka 5 adalah tambahan dari ', or '.
    _max=$((100 + ${#INDENT} + 11))
    if [ $max -gt $_max ];then
        max=100
        min=80
    else
        max=$((max - ${#INDENT} - 11))
        min="$max"
    fi

    declare -i i; i=0
    WRAP_LINE=1
    local count="${#words_array[@]}"
    current_line=
    first_line=1
    for each in "${words_array[@]}"; do
        i+=1
        [ "$i" == "$count" ] && last=1 || last=
        if [ -z "$current_line" ]; then
            if [ -n "$first_line" ];then
                first_line=
                current_line="${inline_description} ${each}"
                __; _, "${inline_description} "; yellow "$each"
            else
                if [ -n "$last" ];then
                    __; _, 'or '; yellow "$each"
                    current_line="or ${each}"
                else
                    __; yellow "$each"
                    current_line="$each"
                fi
            fi
            if [ -n "$last" ];then
                _, '.'; _.
            fi
        else
            if [ -n "$last" ];then
                _current_line="${current_line}, or ${each}"
            else
                _current_line="${current_line}, ${each}"
            fi
            if [ "${#_current_line}" -le $min ];then
                if [ -n "$last" ];then
                    _, ', or '; yellow "$each"; _, '.'; _.
                else
                    _, ', '; yellow "$each"
                fi
                current_line+=", ${each}"
            elif [ "${#_current_line}" -le $max ];then
                if [ -n "$last" ];then
                    _, ', or '; yellow "$each"; _, '.'; _.
                else
                    _, ', '; yellow "$each"; _, ','; _.
                    WRAP_LINE=$((WRAP_LINE+1))
                fi
                current_line=
            else
                WRAP_LINE=$((WRAP_LINE+1))
                if [ -n "$last" ];then
                    _.; __; _, 'or '; yellow "$each"; _, '.'; _.
                    current_line="or ${each}"
                else
                    _, ,; _.; __; yellow "$each"
                    current_line="$each"
                fi
            fi
        fi
    done

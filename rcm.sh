                INDENT+="${RCM_INDENT}" rcm-update $isfast $isquiet "$extension" "$command_required_version" --source=rcm
            fi
            [ ! $? -eq 0 ] && x
            is_updated=1
        elif [[ "$command_required" == rcm ]];then
            owner=ijortengab

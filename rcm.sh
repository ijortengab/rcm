                    fi
                fi
            fi
            if [ -n "$argument_placeholders" ];then
                while read line; do
                    find=$(echo ${line} | sed -E 's|^([^:]+):.*|\1|' | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//')
                    replace=$(echo ${line} | sed -E 's|^[^:]+:(.*)|\1|' | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//')
                    description="${description/"$find"/"$replace"}"
                done <<< "$argument_placeholders"
            fi
            if [ -n "$is_flag" ];then
                _ 'Argument '; magenta ${parameter};_, ' is '; _, optional;_, '.'; _.
                _; _.
                while read line; do
                    wordWrapDescription "$line"
                done <<< "$description"
                _boolean=
                for each in "${argument_prepopulate[@]}";do
                    if grep -q -- "^${parameter}-\$" <<< "$each";then
                        _boolean=0
                        break
                    elif grep -q -- "^${parameter}-=" <<< "$each";then
                        # Ada argument lupa dihapus, contoh: --with-roundcube- mail.example.org
                        # maka set sebagai skip.
                        _boolean=0
                        break
                    elif grep -q -- "^${parameter}\$" <<< "$each";then
                        _boolean=1
                        if [[ "$value_addon" == 'canhavevalue' ]];then
                            value_addon=
                        fi
                        if [[ "$value_addon" == 'multivalue' ]];then
                            ArrayRemove "$parameter" argument_prepopulate[@]
                            argument_prepopulate=("${_return[@]}")
                            unset _return
                        fi
                        break
                    elif grep -q -- "^${parameter}=" <<< "$each";then
                        if [[ "$value_addon" == 'canhavevalue' ]];then
                            _boolean=1
                            value=$(echo "$each" | sed -n -E 's|^[^=]+=(.*)|\1|p')
                            break
                        fi
                    fi
                done
                # Reset first.
                boolean=
                # Variable $boolean digunakan dimana-mana, jadi kita gunakan
                # variable terpisah.
                master_boolean=
                if [[ "$_boolean" == 0 ]];then
                    _; _.
                    __; _, Argument; _, ' '; _, "$parameter"; _, ' ';  _, set to skip by user,' '; _, pass; _, .; _.
                    backup_flag=
                    master_boolean=' '
                elif [[ "$_boolean" == 1 ]];then
                    _; _.
                    if [ -n "$value" ];then
                        wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> prepopulated with value <yellow>${value}</yellow>.'" green
                    else
                        wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> prepopulated." green
                        if [[ "$value_addon" == 'multivalue' ]];then
                            found=
                            for each in "${argument_prepopulate[@]}";do
                                if grep -q -- "^${parameter}\$" <<< "$each";then
                                    found=1
                                    let flags++
                                    wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> prepopulated." green
                                fi
                            done
                            # Biar tidak membingunkan kedepannya, hapus saja semua dari array.
                            if [ -n "$found" ];then
                                ArrayRemoveAll "$parameter" argument_prepopulate[@]
                                argument_prepopulate=("${_return[@]}")
                                unset _return
                            fi
                        fi
                    fi
                    backup_flag=
                    master_boolean=1
                fi

                # Jika $parameter merupakan other option, maka skip semua dialog.
                # jika tidak ada prepopulate value.
                if [ -n "$immediately_other_options" ];then
                    if [ -z "$_boolean" ];then
                        backup_flag=
                        master_boolean=' '
                    fi
                fi

                # Jika non interactive, maka skip.
                if [ -z "$interactive" ];then
                    if [ -z "$_boolean" ];then
                        backup_flag=
                        master_boolean=' '
                    fi
                fi

                if [ -n "$backup_flag" ];then
                    printBackupFlagDialog
                    master_boolean="$boolean"
                    if [[ "$value_addon" == 'canhavevalue' ]];then
                        if [ -n "$backup_value" ];then
                            printBackupDialog
                        fi
                    fi
                fi
                if [ -z "$master_boolean" ];then
                    _; _.
                    __; _, Add this argument?; _.
                    userInputBooleanDefaultNo
                    master_boolean="$boolean"
                    is_press=1
                fi
                if [[ "$master_boolean" == ' ' ]];then
                    master_boolean=
                fi
                # Populate placeholders.
                if [ -n "$argument_placeholders" ];then
                    argument_placeholders+=$'\n'
                fi
                if [ -n "$master_boolean" ]; then
                    is_flagged=1
                    if [[ "$value_addon" == 'canhavevalue' ]];then
                        if [ -z "$value" ];then
                            _; _.
                            __; _, Do you want fill with value?; _.
                            userInputBooleanDefaultNo
                        fi
                        if [ -n "$value" ];then
                            # fill from prepopulated
                            boolean=1
                        fi
                        if [ -n "$boolean" ]; then
                            if [ -z "$value" ];then
                                if [ -n "$history_value" ];then
                                    printHistoryDialog
                                    if [ -n "$value" ];then
                                        _; _.
                                        wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> filled with value <yellow>$value</yellow> which is selected from the list of history." green
                                    fi
                                fi
                            fi
                            if [ -z "$value" ];then
                                if [ "${#available_values[@]}" -gt 0 ];then
                                    printSelectDialog available_values[@]
                                fi
                            fi
                            until [[ -n "$value" ]];do
                                __; read -p "Type the value: " value
                                is_typing=1
                            done
                            # Sanitize user input
                            # Menghapus karakter aneh karena menekan arrow up/down/right/left di keyboard.
                            # Credit: https://stackoverflow.com/a/47918586
                            value=$(echo "$value" | tr -cd '\11\12\15\40-\176' | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//')
                            argument_pass+=("${parameter}=${value}")
                            [[ "$value" =~ ' ' ]] && _value="'$value'" || _value="$value"
                            argument_preview+=("${parameter}=${_value}")
                            argument_preview_real+=("${parameter}=${_value}")
                        else
                            argument_pass+=("${parameter}")
                            argument_preview+=("${parameter}")
                            argument_preview_real+=("${parameter}")
                        fi
                    else
                        i=1
                        until [[ $i -gt $flags ]];do
                            argument_pass+=("${parameter}")
                            argument_preview+=("${parameter}")
                            argument_preview_real+=("${parameter}")
                            let i++
                        done
                    fi
                    # Populate placeholders.
                    if [ -n "$value" ];then
                        argument_placeholders+='['"$parameter"']: '"$value"
                        argument_placeholders+=$'\n'
                        argument_placeholders+='['"$parameter"'^^]: '"${value^^}"
                    else
                        argument_placeholders+='['"$parameter"']: '"1"
                    fi
                else
                    # Populate placeholders.
                    argument_placeholders+='['"$parameter"']: '"0"
                    if [ -z "$argument_preview_bypass" ];then
                        argument_preview+=("${parameter}-")
                    fi
                fi
                if [ -n "$master_boolean" ];then
                    if [ -n "$is_press" ];then
                        if [ -n "$value" ];then
                            if [ -n "$is_typing" ];then
                                _; _.
                                wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> added with value <yellow>$value</yellow> manually." green
                            fi
                        else
                            _; _.
                            wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> added manually." green
                        fi
                    fi
                fi
            elif [[ "$parameter" == '--' ]];then
                _ 'Argument '; magenta ${parameter};_, ' is '; _, optional;_, '.'; _.
                _; _.
                while read line; do
                    wordWrapDescription "$line"
                done <<< "$description"
                __; _, Add value?; _.
                userInputBooleanDefaultNo
                if [ -n "$boolean" ]; then
                    if [ -n "$history_value" ];then
                        printHistoryDialog
                        if [ -n "$value" ];then
                            _; _.
                            wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> filled with value <yellow>$value</yellow> which is selected from the list of history." green
                        fi
                    fi
                    if [ -z "$value" ];then
                        __; read -p "Type the value: " value
                    fi
                    if [ -n "$value" ];then
                        argument_pass+=("${parameter} ${value}")
                        argument_preview+=("${parameter} ${value}")
                        argument_preview_real+=("${parameter} ${value}")
                    fi
                fi
            else
                if [ -n "$is_required" ];then
                    _ 'Argument '; magenta ${parameter};_, ' is '; yellow required;_, '.'; _.
                else
                    _ 'Argument '; magenta ${parameter};_, ' is '; _, optional;_, '.'; _.
                fi
                _; _.
                while read line; do
                    wordWrapDescription "$line"
                done <<< "$description"
                if [ -n "$default_value" ];then
                    wordWrapDescriptionColorize "Default value: <yellow>${default_value}</yellow>."
                fi
                if [ -n "$prepopulate_value" ];then
                    backup_value=
                    history_value=
                fi
                for each in "${argument_prepopulate[@]}";do
                    if grep -q -- "^${parameter}-\$" <<< "$each";then
                        _; _.
                        __; _, Argument; _, ' '; _, "$parameter"; _, ' ';  _, set to skip by user,' '; _, pass; _, .; _.
                        backup_value=
                        history_value=
                        is_required=
                        value=' '
                        break
                    fi
                done
                # Jika tidak multivalue, tapi di prepopulate berkali-kali, maka
                # kita menggunakan last value.
                for each in "${argument_prepopulate[@]}";do
                    if grep -q -- "^${parameter}=" <<< "$each";then
                        value=$(echo "$each" | sed -n -E 's|^[^=]+=(.*)|\1|p')
                        if [[ "$value_addon" == 'multivalue' ]];then
                            values+=("$value")
                        fi
                        _; _.
                        wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> prepopulated with value <yellow>$value</yellow>." green
                        backup_value=
                    fi
                done

                # Jika $parameter merupakan other option, maka skip semua dialog.
                # jika tidak ada prepopulate value.
                if [ -n "$immediately_other_options" ];then
                    if [ -z "$value" ];then
                        backup_value=
                        value=' '
                    fi
                fi

                # Jika non interactive, maka skip.
                if [ -z "$interactive" ];then
                    if [ -z "$value" ];then
                        backup_value=
                        value=' '
                    fi
                fi

                # Backup dialog belum mendukung multivalue.
                if [ -n "$backup_value" ];then
                    printBackupDialog
                fi
                if [ -z "$value" ];then
                    # History dialog belum mendukung multivalue.
                    if [ -n "$history_value" ];then
                        printHistoryDialog
                        if [ -n "$value" ];then
                            _; _.
                            wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> filled with value <yellow>$value</yellow> which is selected from the list of history." green
                        fi
                    fi
                fi
                if [[ -z "$value" && -n "$prepopulate_value" ]];then
                    # Value from prepopulate argument tetap diutamakan
                    # daripada variable.
                    value="$prepopulate_value"
                    _; _.
                    wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> filled with value <yellow>$value</yellow> from environment variable." green
                fi
                # Available value dialog juga belum mendukung multivalue.
                if [ -z "$value" ];then
                    Rcm_get_list_values
                fi
                if [ -n "$is_required" ];then
                    until [[ -n "$value" ]];do
                        __; read -p "Type the value: " value
                        is_typing=1
                    done
                fi
                if [[ "$value" == ' ' ]];then
                    value=
                fi
                if [[ -z "$value" && -n "$default_value" ]];then
                    value="$default_value"
                fi
                # Populate placeholders.
                if [ -n "$argument_placeholders" ];then
                    argument_placeholders+=$'\n'
                fi
                if [ -n "$value" ];then
                    # Sanitize user input
                    # Menghapus karakter aneh karena menekan arrow up/down/right/left di keyboard.
                    # Credit: https://stackoverflow.com/a/47918586
                    if [ "${#values[@]}" -eq 0 ];then
                        values=("$value")
                    fi
                    for value in "${values[@]}";do
                        value=$(echo "$value" | tr -cd '\11\12\15\40-\176' | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//')
                        argument_pass+=("${parameter}=${value}")
                        [[ "$value" =~ ' ' ]] && _value="'$value'" || _value="$value"
                        argument_preview+=("${parameter}=${_value}")
                        argument_preview_real+=("${parameter}=${_value}")
                        if [ "${#available_values[@]}" -gt 0 ];then
                            ArrayRemove "$value" available_values[@]
                            available_values=("${_return[@]}")
                            unset _return
                        fi
                    done
                    # Placeholder tidak berlaku untuk multivalue. @todo, masukkan ke dokumentasi.
                    # Hanya berlaku nilai terakhir.
                    argument_placeholders+='['"$parameter"']: '"$value"
                    argument_placeholders+=$'\n'
                    argument_placeholders+='['"$parameter"'^^]: '"${value^^}"
                else
                    argument_placeholders+='['"$parameter"']: -'
                    if [ -z "$argument_preview_bypass" ];then
                        argument_preview+=("${parameter}-")
                    fi
                fi
                if [[ -n "$value" && -n "$is_typing" ]];then
                    _; _.
                    [ -z "$default_value" ] && suffix=' manually' || suffix=' automatically'
                    wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> filled with value <yellow>$value</yellow>${suffix}." green
                fi
            fi
            # Backup to text file.
            if [ -n "$value" ];then
                # Belum support history untuk kasus multivalue.
                mkdir -p $(dirname "$backup_storage")
                echo "${parameter}=${value}" >> "$backup_storage"
                if [ -f "$history_storage" ];then
                    if grep -q -- "^${parameter}=${value}\$" "$history_storage";then
                        save_history=
                    fi
                    if [[ "$value" =~ []\[] ]];then
                        if grep -q -F -- "${parameter}=${value}" "$history_storage";then
                            save_history=
                        fi
                    fi
                fi
                if [ -n "$save_history" ];then
                    mkdir -p $(dirname "$history_storage");
                    echo "${parameter}=${value}" >> "$history_storage"
                fi
            fi
            # Backup to text file for flag.
            if [ -n "$master_boolean" ];then
                mkdir -p $(dirname "$backup_storage")
                echo "${parameter}" >> "$backup_storage"
            fi
            if [[ "$value_addon" == 'multivalue' ]];then
                again=1
                until [ -z "$again" ]; do
                    is_press=
                    boolean=
                    if [ -n "$is_flag" ];then
                        if [[ -n "$is_flagged" && -n "$confirmation" ]];then
                            # Reset condition before multivalue.
                            is_flagged=
                            _; _.
                            __ Add this argument again?
                            userInputBooleanDefaultNo
                            is_press=1
                        fi
                    else
                        if [[ -n "$value" && -n "$confirmation" ]];then
                            # Reset condition before multivalue.
                            value_before="$value"
                            value=
                            _; _.
                            __ Add another value?
                            userInputBooleanDefaultNo
                            is_press=1
                        fi
                    fi
                    if [ -n "$boolean" ];then
                        if [ -n "$is_flag" ];then
                            argument_pass+=("${parameter}")
                            argument_preview+=("${parameter}")
                            argument_preview_real+=("${parameter}")
                            is_flagged=1
                        elif [[ "$parameter" == '--' ]];then
                            if [ -n "$history_value" ];then
                                printHistoryDialog
                                if [ -n "$value" ];then
                                    _; _.
                                    wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> filled with value <yellow>$value</yellow> which is selected from the list of history." green
                                fi
                            fi
                            if [ -z "$value" ];then
                                _; _.
                                __; read -p "Type the value or leave blank to skip: " value
                                is_typing=1
                            fi
                            if [ -n "$value" ];then
                                argument_pass+=("${value}")
                                argument_preview+=("${value}")
                                argument_preview_real+=("${value}")
                            fi
                        else
                            Rcm_get_list_values "$value_before"
                            if [ -n "$value" ];then
                                # Sanitize user input
                                # Menghapus karakter aneh karena menekan arrow up/down/right/left di keyboard.
                                # Credit: https://stackoverflow.com/a/47918586
                                value=$(echo "$value" | tr -cd '\11\12\15\40-\176' | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//')
                                argument_pass+=("${parameter}=${value}")
                                [[ "$value" =~ ' ' ]] && _value="'$value'" || _value="$value"
                                argument_preview+=("${parameter}=${_value}")
                                argument_preview_real+=("${parameter}=${_value}")
                            fi
                        fi
                        # Backup to text file.
                        if [ -n "$value" ];then
                            mkdir -p $(dirname "$backup_storage");
                            echo "${parameter}=${value}" >> "$backup_storage"
                            if [ -f "$history_storage" ];then
                                if grep -q -- "^${parameter}=${value}\$" "$history_storage";then
                                    save_history=
                                fi
                            fi
                            if [ -n "$save_history" ];then
                                mkdir -p $(dirname "$history_storage");
                                echo "${parameter}=${value}" >> "$history_storage"
                            fi
                        fi
                        if [[ -n "$value" && "$is_typing" ]];then
                            _; _.
                            wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> filled again with value <yellow>$value</yellow> manually." green
                        fi
                        if [[ -n "$is_flagged" && "$is_press" ]];then
                            _; _.
                            wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> added again manually." green
                        fi
                    else
                        again=
                    fi
                done
            fi
            # Other options.
            if [[ -z "$options" && -z "$load_other_options" ]];then
                if [ -n "$subcommand" ];then
                    other_options=`$command --help 2>/dev/null | sed -n '/^Other [Oo]ptions for command '$subcommand'.*[:\.]$/,$p' | sed -n '1,/^\s*$/p' | sed -n '2,/^\s*$/p'`
                else
                    other_options=`$command --help 2>/dev/null | sed -n '/^Other [Oo]ptions.*[:\.]$/,$p' | sed -n '1,/^\s*$/p' | sed -n '2,/^\s*$/p'`
                fi
                if [ -n "$other_options" ];then
                    options="$other_options"
                    load_other_options=1
                    if [ -n "$confirmation" ];then
                        _; _.
                        _; _, 'There are '; yellow other ;_, ' arguments available and optional.'; _.
                        _; _.
                        __; _, Prompt other arguments?; _.
                        userInputBooleanDefaultNo
                        if [ -z "$boolean" ]; then
                            immediately_other_options=1
                            argument_preview_bypass=1
                        fi
                    else
                        argument_preview_bypass=1
                        immediately_other_options=1
                    fi
                fi
            fi
        done
        ____
    fi
}
Rcm_prompt_sigint() {
    local shortoptions
    [ -n "$resolve_dependencies" ] && shortoptions+='r'
    [ -z "$interactive" ] && shortoptions+='x'
    [ -z "$fast" ] && shortoptions+='s'
    if [ -n "$verbose" ];then
        for ((i = 0 ; i < "$verbose" ; i++)); do
            shortoptions+='v'
        done
    fi
    [ -n "$shortoptions" ] && shortoptions=" -${shortoptions}"
    _.;
    _.;
    error Interrupt by User.; _.
    wordWrapDescription 'Use command below to return to the last dialog.' 0
    if [ -z "$RCM_PROMPT_CHAIN" ];then
        RCM_PROMPT_CHAIN="rcm${shortoptions} ${command_raw} --"
    fi
    for each in "${argument_preview[@]}"; do RCM_PROMPT_CHAIN+=" ${each}"; done
    words_array=($RCM_PROMPT_CHAIN)
    wordWrapCommand
    exit 0
}
Rcm_get_list_values() {
    if [[ -n "$_available_values_from_command" && -z "$_available_values_from_command_executed" ]];then
        _available_values_from_command_executed=1
        if command -v "$_command" > /dev/null;then
            _; _.
            [ -n "$_arguments" ] && _arguments=' '"$_arguments"
            wordWrapDescriptionColorize "Value available from command: <magenta>${_command}${_arguments}</magenta>"
            mktemp=$(mktemp -p /dev/shm)
            ${_command}${_arguments} > "$mktemp"
            exit_code=$?
            while read line;do
                [ -n "$line" ] && available_values+=("$line")
            done < "$mktemp"
            rm "$mktemp"
        fi
    fi
    if [ -z "$available_values_backup" ];then
        available_values_backup=("${available_values[@]}")
    fi
    while [[ $# -gt 0 ]]; do
        ArrayRemove "$1" available_values[@]
        available_values=("${_return[@]}")
        unset _return
        shift
    done
    if [ "${#available_values[@]}" -gt 0 ];then
        if [ -n "$or_other" ];then
            printSelectOtherDialog available_values[@]
        elif [[ "${#available_values[@]}" -eq 1 && -n "$is_required" ]];then
            value="${available_values[0]}"
            _; _.
            __; _, "Available value: "; yellow "$value";  _, '.'; _.
            if [ -n "$interactive" ];then
                if [ -n "$is_required" ];then
                    _; _.
                    wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> filled with the only available value <yellow>$value</yellow> automatically." green
                else
                    _; _.
                    wordWrapDescription 'The one and only available value is selected.'
                    userInputBooleanDefaultYes
                    if [ -z "$boolean" ];then
                        value=' '
                    fi
                fi
            else
                _; _.
                wordWrapDescriptionColorize "Argument <magenta>${parameter}</magenta> filled with the only available value <yellow>$value</yellow> automatically." green
            fi
        else
            printSelectDialog available_values[@]
        fi
    else
        _; _.
        if [[ -n "$_available_values_from_command" && ! $exit_code -eq 0 ]];then
            is_required=
            __; _, Argument; _, ' '; _, "$parameter"; _, ' ';  _, set to skip by command,' '; _, pass; _, .; _.
        elif [[ -n "$_available_values_from_command" && -z "$or_other" ]];then
            is_required=
            __; _, No value available,' '; _, pass; _, .; _.
        else
            if [ -n "$default_value" ];then
                __; _, Leave blank will use default value.; _.
                label=$(_, 'Type the value [' 2>&1; yellow "$default_value" 2>&1; _, ']: ' 2>&1)
                __; read -p "$label" value
                [ -z "$value" ] && value=' '
            elif [ -n "$is_required" ];then
                __; read -p "Type the value: " value
            else
                __; read -p "Type the value or leave blank to skip: " value
            fi
            is_typing=1
        fi
    fi
}
Rcm_event_dispatcher() {
    # global command argument_placeholders command_prepend tempfile
    local key value
    local label="$1"; shift
    local to_execute command_raw _command_arguments _command _arguments
    local line  find replace
    to_execute=`${command} --help 2>/dev/null | sed -n '/^'"$label"'[:\.]$/,$p' | sed -n '1,/^\s*$/p' | sed -n '2,/^\s*$/p'`
    if [ -n "$to_execute" ];then
        until [[ -z "$to_execute" ]];do
            command_raw=`sed -n 1p <<< "$to_execute" | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//'`
            to_execute=`sed -n '2,$p' <<< "$to_execute"`
            _command_arguments=$(echo "$command_raw" | sed -n -E 's/\s*([^\)]+\))/\1/p')
            _command=$(echo "$_command_arguments" | sed -n -E 's/^([^\(]+)\(([^\)]*)\)$/\1/p')
            _arguments=$(echo "$_command_arguments" | sed -n -E 's/^([^\(]+)\(([^\)]*)\)$/\2/p')
            if command -v "$_command" > /dev/null;then
                if [ -n "$argument_placeholders" ];then
                    while read line; do
                        find=$(echo ${line} | sed -E 's|^([^:]+):.*|\1|' | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//')
                        replace=$(echo ${line} | sed -E 's|^[^:]+:(.*)|\1|' | sed 's/^[[:blank:]]*//;s/[[:blank:]]*$//')
                        # description="${description/"$find"/"$replace"}"
                        if [ -n "$_arguments" ];then
                            _arguments="${_arguments/"$find"/"$replace"}"
                        fi
                    done <<< "$argument_placeholders"
                fi
            fi
            [ -n "$_arguments" ] && _arguments=' '"$_arguments"
            chapter "$label" command.
            code ${_command}${_arguments}
            ____

            if [ -z "$tempfile" ];then
                tempfile=$(mktemp -p /dev/shm -t rcm.XXXXXX)
            fi
            RCM_PROMPT_CHAIN= INDENT+="$RCM_INDENT" ${_command}${_arguments} \
                > "$tempfile" \
                ; [ ! $? -eq 0 ] && { rm "$tempfile"; x; }

            while IFS= read -r to_export; do
                key=$(cut -d= -f1 <<< "$to_export")
                value=$(cut -d= -f2- <<< "$to_export")
                [ -z "$value" ] && value=-
                code export "$key"="$value"
                export "$key"="$value"
                [ -n "$command_prepend" ] && command_prepend+=" "
                command_prepend+="${key}=${value}"
            done < "$tempfile"
            if [ -s "$tempfile" ];then
                ____
            fi

        done
    fi
}
Rcm_init() {
    # global display_waiting
    local owner repository tag_name rcm_extension
    owner=ijortengab
    repository=rcm
    tag_name=`printVersion`
    rcm_extension=$1
    local cache_directory="${HOME}/.cache/rcm/${owner}/${repository}/${tag_name}"
    Rcm_github_download "$owner" "$repository" "$tag_name" "$cache_directory"
    local source="${cache_directory}/${rcm_extension}.sh"
    if [ ! -f "$source" ];then
        error File is not found: "$source".; x
    fi
    local target="${BINARY_DIRECTORY}/${rcm_extension}"
    if [ -f "$target" ];then
        backupFile move "$target"
    fi
    if [ -z "$display_waiting" ];then
        code cp "$source" "$target"
    fi
    cp "$source" "$target"
    if [ -z "$display_waiting" ];then
        _ 'Success install '; magenta "$rcm_extension"; _, ' version: '; yellow "$tag_name"; _.
    fi
}
Rcm_github_download() {
    # global display_waiting
    local owner=$1 repository=$2 tag_name=$3 output_dir=$4
    if [ -z "$owner" ];then
        error "Operand <owner> required."; x
    fi
    if [ -z "$repository" ];then
        error "Operand <repository> required."; x
    fi
    if [ -z "$tag_name" ];then
        error "Operand <tag_name> required."; x
    fi
    if [ -z "$output_dir" ];then
        error "Operand <output_dir> required."; x
    fi
    local url="https://api.github.com/repos/${owner}/${repository}/releases/tags/${tag_name}"
    local tag_name_validate=$(Rcm_wget 3600 "$url" | grep '^  "tag_name": ".*",$' | sed -E 's/  "tag_name": "(.*)",/\1/')
    if [ -z "$tag_name_validate" ];then
        if [ -n "$display_waiting" ];then
            printf "\r\033[K" >&2
        fi
        error "The repository does not have that release tag: ${tag_name}."
        if [ -n "$display_waiting" ];then
            kill -SIGTERM $$
        fi
        # Pastikan exit.
        x
    fi
    if [ -z "$display_waiting" ];then
        _ "Download Github repository ${owner}/${repository}."; _.
    fi
    local tempdir found_directory_extracted cache_directory url_tarball output_dir_parent
    url_tarball="https://api.github.com/repos/${owner}/${repository}/tarball/${tag_name}"
    if [ ! -d "$output_dir" ];then
        if [ -z "$display_waiting" ];then
            _ 'Downloading version: '; yellow "$tag_name"; _.
        fi
        tempdir=$(mktemp -d)
        cd "$tempdir"
        wget -q -O "${tag_name}.tar.gz" "$url_tarball"
        if [ ! -f "${tag_name}.tar.gz" ];then
            error Failed to download file: "${tag_name}.tar.gz".
            cd - >/dev/null
            rm -rf "$tempdir"
            x
        fi
        tar xfz "${tag_name}.tar.gz"
        found_directory_extracted=$(find -maxdepth 1 -mindepth 1 -type d)
        if [ ! -d "$found_directory_extracted" ];then
            error Failed to extract archieve: "${tag_name}.tar.gz".;
            cd - >/dev/null
            rm -rf "$tempdir"
            x
        fi
        output_dir_parent="$(dirname "$output_dir")"
        mkdir -p "$output_dir_parent"
        if [ ! -d "$output_dir_parent" ];then
            error Failed to create output directory parent: "$output_dir_parent".;
        fi
        mv $(realpath "$found_directory_extracted") "$output_dir"
        # Cleaning.
        cd - >/dev/null
        rm -rf "$tempdir"
    else
        if [ -z "$display_waiting" ];then
            _ 'Using downloaded version: '; yellow "$tag_name"; _.
        fi
    fi
}


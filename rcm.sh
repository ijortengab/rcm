        if [ -n "$_download" ];then
            while IFS= read -r _line; do
                if ! grep -q -F -- "$_line" <<< "$table_downloads";then
                    [ -n "$_line" ] && table_downloads+="$_line"$'\n'
                fi
            done <<< "$_download"
        fi
